import { expect, test } from "@playwright/test";
import { openDesktop, projectName } from "./harness.ts";

test("review findings stay mounted when a stale banner appears", async ({ page }) => {
  const finding = { id: 1, area: "src", severity: "high", title: "Example finding", file: "sample.ts", line: 2, why: "Needs attention", verdict: "verified", dropped_why: "", dismissed: false };
  const review = { id: "review-one", project: projectName, branch: "feature", base: "main", head: "abc123", head_at: 1, started_at: 1, machine_name: "build-box", changed_lines: 2, files: 1, merge: "clean", conflicts: [], pr: null, shards: [], findings: [finding] };
  const branches = { machine_id: "build-box", machine_name: "build-box", default_branch: "main", branches: [{ name: "feature", worktree: "/srv/project", ahead: 1, behind: 0, head: "abc123", subject: "Commit", committed_at: 1, local: true, pushed: true }] };
  await openDesktop(page, false, { project_branches: branches, reviews_list: [review], review_get: review, review_check: { head: "def456", stale: true }, project_git_history: { machine_id: "build-box", machine_name: "build-box", root: "/srv/project", refs: [{ name: "feature", head: "abc123", kind: "local" }], worktrees: [], commits: [{ id: "abc123", parents: [], author: "Example", committed_at: 1, subject: "Commit" }], next: null }, project_git_files: [], project_git_diff: { root: "/srv/project", base: "", merge_base: "", working_tree: false, additions: 0, deletions: 0, more: 0, files: [] } });
  await page.evaluate(() => {
    const invoke = window.__TAURI__.core.invoke;
    window.__TAURI__.core.invoke = async <T>(command: string, args?: Record<string, unknown>) => {
      if (command === "review_check") await new Promise<void>(resolve => window.addEventListener("test-review-check", () => resolve(), { once: true }));
      if (command === "review_dismiss") throw new Error("Review update failed");
      if (command === "review_fix") return { id: "task-one", slug: "task", title: "Fix finding", state: "running" } as T;
      return invoke<T>(command, args);
    };
  });
  await page.evaluate(project => window.__navigation.open({ projects: { project } }), projectName);
  await page.locator(".pj-strip button").filter({ hasText: "branch" }).click();
  const button = page.getByRole("button", { name: "Review branch" });
  await expect(button).toBeVisible();
  await button.click();
  const findingButton = page.getByRole("button", { name: "Dismiss" });
  await expect(findingButton).toBeVisible();
  const detail = page.locator(".pj-det");
  await detail.evaluate(el => { el.style.height = "100px"; el.style.overflow = "auto"; el.scrollTop = 40; });
  const again = page.getByRole("button", { name: "Run again" });
  await again.focus();
  await again.evaluate(el => { el.dataset.identity = "kept"; });
  await findingButton.evaluate(el => { el.dataset.identity = "kept"; });
  const before = await detail.evaluate(el => el.scrollTop);
  await page.evaluate(() => window.dispatchEvent(new Event("test-review-check")));
  await expect(page.getByText(/moved to def456/)).toBeVisible();
  await expect(findingButton).toHaveAttribute("data-identity", "kept");
  await expect(again).toHaveAttribute("data-identity", "kept");
  await expect(again).toBeFocused();
  await expect(detail).toHaveJSProperty("scrollTop", before);
  await expect(page.getByRole("button", { name: "Merge…" })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Post review…" })).toBeDisabled();
  await findingButton.click();
  await expect(page.getByText("Review update failed")).toBeVisible();
  await expect(findingButton).toHaveAttribute("data-identity", "kept");
  await page.getByRole("button", { name: "Fix with worker" }).click();
  await expect(page.getByText("Started Fix finding. It shows under Tasks.")).toBeVisible();
  await page.locator(".pj-strip button").filter({ hasText: "branch" }).click();
  await expect(page.getByRole("button", { name: "Review branch" })).toBeVisible();
  await page.getByRole("button", { name: "Review branch" }).click();
  await expect(page.getByRole("button", { name: "Run again" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Run again" })).not.toHaveAttribute("data-identity", "kept");
});
