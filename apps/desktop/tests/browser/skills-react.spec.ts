import { expect, test } from "@playwright/test";
import { openDesktop } from "./harness.ts";

test("skills retain list position and editor drafts through updates", async ({ page }) => {
  const skills = Array.from({ length: 25 }, (_, i) => ({ id: `skill-${i}`, name: `Skill ${i}`, description: "When needed", body: "Original", html: "<p>Original</p>", group_id: null, group_name: null, enabled: true, uses: 0, last_used: null, updated_at: "", edited: false, can_undo: false }));
  await openDesktop(page, false, { status: { link: "linked", signed_out: false, server: true, live: false, session: null }, list_skills: skills });
  await page.evaluate(() => window.__navigation.open("skills"));
  const row = page.getByRole("option", { name: /Skill 0/ });
  await expect(row).toBeVisible();
  const list = page.locator("#klist");
  await list.evaluate(element => { element.style.height = "120px"; element.style.overflow = "auto"; element.scrollTop = 150; });
  const top = await list.evaluate(element => element.scrollTop);
  await page.locator("#bar .dhints").evaluate(element => Reflect.set(window, "skillsHints", element));
  await page.keyboard.press("Tab");
  expect(await page.locator("#bar .dhints").evaluate(element => element === Reflect.get(window, "skillsHints"))).toBe(true);
  await expect(list).toHaveJSProperty("scrollTop", top);
  await page.keyboard.press("Tab");
  await row.click();
  await page.getByRole("button", { name: "Edit" }).click();
  const name = page.locator("#kname"), body = page.locator("#kbody");
  await name.fill("");
  await body.fill("Keep this draft");
  await body.evaluate(element => { if (element instanceof HTMLTextAreaElement) element.setSelectionRange(2, 5); });
  await page.getByRole("button", { name: "Save" }).click();
  await expect(page.locator(".derr")).toContainText("Give the skill a name.");
  await expect(body).toHaveValue("Keep this draft");
  await expect(body).toHaveJSProperty("selectionStart", 2);
  await page.getByRole("button", { name: "Cancel" }).click();
  await expect(page.locator(".reply")).toContainText("Original");
});
