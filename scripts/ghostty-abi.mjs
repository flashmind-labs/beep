// Writes apps/desktop/src/stores/terminals/ghostty-abi.ts from Ghostty's description
// of its C ABI on wasm32 (src/terminal/c/abi/wasm32-freestanding.json), so the
// wrapper reads enum values, struct offsets and bit fields from upstream
// instead of copies by hand. Run by scripts/build-ghostty-wasm.sh.
//
// Usage: node scripts/ghostty-abi.mjs <abi.json> <out.ts> <ghostty commit>
import { readFileSync, writeFileSync } from "node:fs";

const [abiPath, outPath, commit] = process.argv.slice(2);
if (!abiPath || !outPath || !commit) {
  console.error("usage: node scripts/ghostty-abi.mjs <abi.json> <out.ts> <ghostty commit>");
  process.exit(1);
}

const abi = JSON.parse(readFileSync(abiPath, "utf8"));
if (abi.schema !== 1 || abi.abi.target !== "wasm32" || abi.abi.endian !== "little") {
  console.error(`ghostty-abi: unexpected ABI description ${JSON.stringify(abi.abi)} (schema ${abi.schema})`);
  process.exit(1);
}

const lines = [
  `// Generated by scripts/ghostty-abi.mjs from Ghostty ${commit}`,
  "// (src/terminal/c/abi/wasm32-freestanding.json). Do not edit.",
  "",
];

for (const [name, type] of Object.entries(abi.types).sort(([a], [b]) => a.localeCompare(b))) {
  switch (type.kind) {
    case "enum": {
      // The C enums pin their size with a MAX_VALUE entry; it is no value.
      const values = Object.entries(type.values).filter(([key]) => !key.endsWith("MAX_VALUE"));
      lines.push(`export const ${name} = {`);
      for (const [key, value] of values) lines.push(`  ${key}: ${value},`);
      lines.push("} as const;");
      lines.push(`export type ${name} = (typeof ${name})[keyof typeof ${name}];`, "");
      break;
    }

    case "struct":
    case "union": {
      lines.push(`export const ${name} = {`, `  size: ${type.size},`, "  field: {");
      for (const [field, layout] of Object.entries(type.fields ?? {})) lines.push(`    ${field}: ${layout.offset},`);
      lines.push("  },", "} as const;", "");
      break;
    }

    case "packed": {
      // Each bit field as [lowest bit, width]. A union field also lists
      // each arm's fields, relative to the union's lowest bit.
      lines.push(`export const ${name} = {`, `  size: ${type.size},`, "  bits: {");
      for (const [field, bits] of Object.entries(type.bits ?? {})) lines.push(`    ${field}: [${bits.lsb}, ${bits.width}],`);
      lines.push("  },");

      const unions = Object.entries(type.bits ?? {}).filter(([, bits]) => bits.kind === "union");
      if (unions.length > 0) {
        lines.push("  arms: {");
        for (const [field, bits] of unions) {
          lines.push(`    ${field}: {`);
          for (const [arm, layout] of Object.entries(bits.arms)) {
            const fields = Object.entries(layout?.bits ?? {}).map(([f, b]) => `${f}: [${b.lsb}, ${b.width}]`);
            lines.push(`      ${arm}: { ${fields.join(", ")} },`);
          }
          lines.push("    },");
        }
        lines.push("  },");
      }

      lines.push("} as const;", "");
      break;
    }

    case "alias":
    case "callback":
    case "opaque":
      // Handles and function pointers are plain i32 in wasm32.
      break;

    default:
      console.error(`ghostty-abi: ${name} has an unknown kind ${type.kind}`);
      process.exit(1);
  }
}

writeFileSync(outPath, lines.join("\n"));
